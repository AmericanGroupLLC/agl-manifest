#!/usr/bin/env python3
"""Daily stand-up for the AI office, built only from measured state.

    python3 ai-office/scripts/standup.py            # -> ai-office/reports/<date>-standup.md
    python3 ai-office/scripts/standup.py --stdout   # print instead

Sources (nothing is typed in by hand):
  automations   GitHub Actions: ship.yml, domain-monitor.yml (agl-manifest),
                deploy.yml (website, backend), backend CI
  apple         docs/asc-build-state.json, docs/store-holds.json
  gates         docs/apple-requirements.json, docs/screenshot-audit.json
  domains       docs/domain-health.json
  founder       open MA-xxx items in docs/MANUAL_ACTIONS.md
  queue         GitHub issues labelled ai-office

A source that cannot be read is reported as "unknown", never guessed.
"""

from __future__ import annotations

import collections
import datetime as dt
import json
import pathlib
import re
import subprocess
import sys

M = pathlib.Path(__file__).resolve().parents[2]          # agl-manifest
OFFICE = M / "ai-office"
ORG = "AmericanGroupLLC"


def load(rel: str):
    try:
        return json.loads((M / rel).read_text())
    except Exception:
        return None


def gh(*args: str) -> str:
    try:
        r = subprocess.run(["gh", *args], capture_output=True, text=True, timeout=60)
        return r.stdout if r.returncode == 0 else ""
    except Exception:
        return ""


def last_runs(repo: str, workflow: str, n: int = 3) -> str:
    out = gh("run", "list", "-R", f"{ORG}/{repo}", "--workflow", workflow, "--limit", str(n),
             "--json", "conclusion,status,createdAt,event")
    try:
        runs = json.loads(out)
    except Exception:
        return "unknown (gh unavailable)"
    if not runs:
        return "no runs"
    return ", ".join(f"{(r.get('conclusion') or r.get('status'))} ({r['createdAt'][5:16]} {r['event']})" for r in runs)


def main() -> int:
    today = dt.date.today().isoformat()
    L = [f"# Stand-up — {today}", "",
         "_Generated by `ai-office/scripts/standup.py` from measured state. Unknown means the source could not be read._", ""]

    # --- automations -----------------------------------------------------
    L += ["## Automation health", "", "| Job | Last runs |", "| --- | --- |"]
    for repo, wf, label in (("agl-manifest", "ship.yml", "Delivery pipeline (daily 06:00 UTC)"),
                            ("agl-manifest", "domain-monitor.yml", "Domain monitor (30 min)"),
                            ("americangroup.ai", "deploy.yml", "Website deploy"),
                            ("AmericanGroupLLC-Backend", "ci.yml", "Backend CI"),
                            ("AmericanGroupLLC-Backend", "deploy.yml", "Backend → Supabase (approval)")):
        L.append(f"| {label} | {last_runs(repo, wf)} |")
    sw = OFFICE.parent / ".." / ".dist" / "store-watch" / "latest.log"
    sw = pathlib.Path.home() / "agl/.dist/store-watch/latest.log"
    if sw.exists():
        tail = sw.read_text(errors="ignore").strip().splitlines()[-1:]
        L.append(f"| Store watch (6 h, local) | {dt.datetime.fromtimestamp(sw.stat().st_mtime):%m-%d %H:%M} · {tail[0] if tail else ''} |")
    else:
        L.append("| Store watch (6 h, local) | unknown (no log on this machine) |")
    L.append("")

    # --- Apple state -----------------------------------------------------
    asc = load("docs/asc-build-state.json") or []
    holds = load("docs/store-holds.json") or {}
    states = collections.Counter((r.get("review_state") or r.get("state") or "?") for r in asc)
    g = collections.Counter(h.get("guideline") for h in holds.values())
    L += ["## App Store", "",
          f"- Review states: {', '.join(f'{k} {v}' for k, v in states.most_common()) or 'unknown'}",
          f"- Holds (no automatic resubmission): {', '.join(f'{k}: {v}' for k, v in g.most_common()) or 'none'}",
          f"- Account freeze (5.6): **{'ON' if g.get('5.6') else 'off'}**", ""]

    # --- gates -----------------------------------------------------------
    req = load("docs/apple-requirements.json") or {}
    fails = collections.Counter()
    for rows in req.values():
        for r in rows:
            if r.get("state") == "FAIL":
                fails[r["check"]] += 1
    shots = load("docs/screenshot-audit.json") or {}
    shot_fail = sorted(r for r, v in shots.items() if v.get("verdict") == "FAIL")
    L += ["## Requirement gates", "", "| Requirement | Apps failing |", "| --- | --- |"]
    L += [f"| {k} | {v} |" for k, v in fails.most_common()] or ["| all | 0 |"]
    L += ["", f"- Screenshots on App Store Connect failing 2.3.3: {len(shot_fail)}"
          + (f" ({', '.join(shot_fail[:12])}{'…' if len(shot_fail) > 12 else ''})" if shot_fail else ""), ""]

    # --- domains ---------------------------------------------------------
    dh = load("docs/domain-health.json")
    if dh:
        bad = [r for r in dh.get("rows", []) if r.get("state") == "FAIL"]
        L += ["## Domains and services", "",
              f"- Last local check {dh.get('checked_at')}: {len(dh.get('rows', []))} checks, {len(bad)} failing"
              + ("".join(f"\n  - {r['check']}: {r['detail']}" for r in bad)), ""]

    # --- founder decisions -----------------------------------------------
    ma = (M / "docs/MANUAL_ACTIONS.md").read_text(errors="ignore") if (M / "docs/MANUAL_ACTIONS.md").exists() else ""
    items = re.findall(r"^## (MA-0(?:4[0-9]|5[0-9])) · ([^·\n]+)· (.+)$", ma, re.M)
    L += ["## Waiting on the founder", ""]
    L += [f"- **{i}** ({p.strip()}): {t.strip()}" for i, p, t in items if not p.strip().startswith("DONE")] or ["- none recorded"]
    L.append("")

    # --- queue -----------------------------------------------------------
    out = gh("issue", "list", "-R", f"{ORG}/agl-manifest", "--state", "open", "--limit", "50",
             "--json", "number,title,labels")
    try:
        issues = json.loads(out)
    except Exception:
        issues = None
    L += ["## Work queue (GitHub issues)", ""]
    if issues is None:
        L.append("- unknown (gh unavailable)")
    else:
        office = [i for i in issues if any(l["name"] == "ai-office" for l in i.get("labels", []))]
        monitor = [i for i in issues if i["title"].startswith("Domain monitor")]
        L += [f"- #{i['number']} {i['title']}" for i in office + monitor] or ["- empty"]
    L.append("")

    text = "\n".join(L) + "\n"
    if "--stdout" in sys.argv:
        print(text)
        return 0
    out_path = OFFICE / "reports" / f"{today}-standup.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text)
    print(f"-> {out_path.relative_to(M)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
