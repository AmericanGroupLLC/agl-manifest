#!/usr/bin/env python3
"""Regenerate docs/APP_IDENTIFIERS.md and docs/app-identifiers.json.

    python3 scripts/app_identifiers.py

The document claimed to be "generated from the repositories themselves - every
bundle id below is what the app actually builds today" while being hand-kept
and out of date: it listed six apps under the retired `com.americangroup.*`
scheme, a `com.americangroup.ratiotune` that has never existed anywhere, and
"Flutter apps: 36" plus five apps "not yet Flutter" long after all 43 were.

Now it really is generated. Bundle ids come from `apps.json`, which is itself
generated from an audit of the repositories; AdMob ids and the value actually
set in `Info.plist` come from `docs/release-readiness.json`, which is measured
per repo. Nothing here is typed by hand, so it cannot drift again.
"""

from __future__ import annotations

import json
import pathlib

M = pathlib.Path(__file__).resolve().parent.parent
TEST_ADMOB = "3940256099942544"


def main() -> int:
    apps = json.loads((M / "apps.json").read_text())["apps"]
    rows = json.loads((M / "docs/release-readiness.json").read_text())
    rows = rows if isinstance(rows, list) else rows.get("apps", list(rows.values()))
    ready = {r["repo"]: r for r in rows}

    records = []
    for a in sorted(apps, key=lambda x: x["repo"].lower()):
        r = ready.get(a["repo"], {})
        gad = r.get("ios_admob_id") or ""
        records.append({
            "repo": a["repo"],
            "ios_bundle": a["bundle_id"],
            "android_id": a["application_id"],
            "admob_ios": r.get("ios_admob_id") or "",
            "admob_android": r.get("android_admob_id") or "",
            "gad_in_plist": gad,
            "flutter": bool(a.get("flutter", True)),
        })

    def cell(v: str) -> str:
        if not v:
            return "— none set"
        return "`TEST`" if TEST_ADMOB in v else f"`{v}`"

    flutter = [x for x in records if x["flutter"]]
    with_android = [x for x in flutter if x["admob_android"] and TEST_ADMOB not in x["admob_android"]]
    with_ios = [x for x in flutter if x["admob_ios"] and TEST_ADMOB not in x["admob_ios"]]
    mismatched = [x for x in records if x["ios_bundle"] != x["android_id"]]

    L = [
        "# App identifiers and AdMob",
        "",
        "Generated by `scripts/app_identifiers.py` from `apps.json` and",
        "`docs/release-readiness.json` — every id below is what the app actually",
        "builds today. Do not hand-edit; re-run the script.",
        "",
        f"- Flutter apps: **{len(flutter)}** of {len(records)}",
        f"- Apps with a real AdMob **Android** app id: **{len(with_android)}** of {len(flutter)}",
        f"- Apps with a real AdMob **iOS** app id: **{len(with_ios)}** of {len(flutter)}",
        "",
        "Every app uses the `com.americangroupllc.<app>` scheme on both platforms,",
        "and so does every store record. Four App Store Connect records were on",
        "the retired `com.americangroup.*` scheme until 2026-09-26; a sweep of",
        "all 43 legacy ids against the live API now returns none.",
        "",
        "Machine-readable: [`app-identifiers.json`](app-identifiers.json), "
        "[`admob-ids.json`](admob-ids.json)",
        "",
        "## Every app",
        "",
        "`GAD in plist` is what `GADApplicationIdentifier` is set to right now.",
        "`TEST` means Google's public test id — safe, but earns nothing.",
        "",
        "| App | iOS bundle id | Android applicationId | AdMob iOS | AdMob Android | GAD in plist |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for x in records:
        same = x["ios_bundle"] == x["android_id"]
        android = (f"`{x['android_id']}`" if same
                   else f"`{x['android_id']}` ⚠️ differs")
        L.append(
            f"| {x['repo']} | `{x['ios_bundle']}` | {android} | "
            f"{cell(x['admob_ios'])} | {cell(x['admob_android'])} | "
            f"{cell(x['gad_in_plist'])} |")

    L += ["",
          "## Where the two platforms disagree",
          ""]
    if mismatched:
        L += ["| App | iOS bundle id | Android applicationId |",
              "| --- | --- | --- |"]
        L += [f"| {x['repo']} | `{x['ios_bundle']}` | `{x['android_id']}` |"
              for x in mismatched]
    else:
        L.append("None — every app uses one identifier on both platforms.")
    L.append("")

    (M / "docs/APP_IDENTIFIERS.md").write_text("\n".join(L))
    (M / "docs/app-identifiers.json").write_text(
        json.dumps(records, indent=1) + "\n")
    print(f"{len(records)} apps -> docs/APP_IDENTIFIERS.md + docs/app-identifiers.json")
    print(f"  flutter {len(flutter)}, real AdMob android {len(with_android)}, "
          f"ios {len(with_ios)}, platform mismatches {len(mismatched)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
