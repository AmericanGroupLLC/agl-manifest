#!/usr/bin/env python3
"""Generate manifest/apps.yaml from apps.json.

Phase 2 introduces desired-state config under manifest/ while keeping apps.json
as compatibility input for existing automation.
"""

from __future__ import annotations

import argparse
import json
import pathlib


def _q(value: str) -> str:
    if value == "":
        return '""'
    safe = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{safe}"'


def _bool(v: bool) -> str:
    return "true" if v else "false"


def _lines_for_app(app: dict) -> list[str]:
    repo = app["repo"]
    branch = app.get("branch", "main")
    flutter_path = app.get("dir", ".")
    package = app.get("application_id", "")
    bundle = app.get("bundle_id", "")
    version = app.get("version", "")
    firebase_android = bool(app.get("pending", {}).get("firebase_android", False))
    firebase_ios = bool(app.get("pending", {}).get("firebase_ios", False))
    admob = app.get("admob") or {}
    deliverable = app.get("deliverable") or {}

    return [
        f"  {repo}:",
        "    repository:",
        f"      name: {repo}",
        f"      branch: {branch}",
        f"      flutter_path: {flutter_path}",
        "    identity:",
        f"      android_package: {_q(package)}",
        f"      ios_bundle_id: {_q(bundle)}",
        f"    version: {_q(version)}",
        "    release:",
        f"      android_enabled: {_bool(bool(deliverable.get('android')))}",
        f"      ios_enabled: {_bool(bool(deliverable.get('ios')))}",
        "    firebase:",
        f"      android_config_present: {_bool(not firebase_android)}",
        f"      ios_config_present: {_bool(not firebase_ios)}",
        "    admob:",
        f"      integrated: {_bool(bool(admob.get('integrated')))}",
        f"      android_app_id: {_q(admob.get('android_app_id', ''))}",
        f"      ios_app_id: {_q(admob.get('ios_app_id', ''))}",
    ]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--infile", default="apps.json")
    ap.add_argument("--out", default="manifest/apps.yaml")
    args = ap.parse_args()

    infile = pathlib.Path(args.infile).expanduser().resolve()
    out = pathlib.Path(args.out).expanduser().resolve()

    data = json.loads(infile.read_text())
    apps = sorted((a for a in data.get("apps", []) if a.get("flutter")), key=lambda x: x["repo"].lower())
    org = data.get("org", "AmericanGroupLLC")
    flutter_version = data.get("flutter_version", "")

    lines = [
        "# Generated by scripts/generate_apps_yaml.py from apps.json.",
        "# This file is intended to become the desired-state release manifest.",
        "version: 1",
        "",
        "organization:",
        f"  github: {org}",
        "",
        "defaults:",
        "  framework: flutter",
        "  language: dart",
    ]
    if flutter_version:
        lines.append(f"  flutter_version: {flutter_version}")
    lines.extend(
        [
            "",
            "apps:",
        ]
    )
    for app in apps:
        lines.extend(_lines_for_app(app))

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(apps)} flutter apps -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
