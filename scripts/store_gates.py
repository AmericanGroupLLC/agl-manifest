#!/usr/bin/env python3
"""Every store gate, measured where a machine can measure it.

Two different bars are in play and confusing them is how an app gets rejected:

  TESTING     TestFlight beta distribution and Play internal testing.
  PRODUCTION  App Store review and a Play production release.

This reads what the delivery scripts and the two APIs actually reported and
writes docs/STORE_GATES.md. Gates that no API exposes are listed by name under
"console only" rather than being quietly omitted.

    bundle exec ruby scripts/testflight/store_gates.rb   # refresh the Apple side
    python3 scripts/store_gates.py                       # -> docs/STORE_GATES.md
"""
import datetime, glob, json, pathlib, struct, zipfile

ROOT = pathlib.Path("/Users/spatchava/agl"); M = ROOT / "agl-manifest"; D = ROOT / ".dist"
def load(p, d=None):
    try: return json.load(open(D / p))
    except Exception: return d if d is not None else {}

apps  = json.load(open(M / "apps.json"))["apps"]
asc   = load("asc-gates.json")
tf    = load("testflight-state.json")
play  = load("play-results.json")
rel   = load("play-release-results.json")
lst   = load("play-listing-results.json")

def so_alignment(aab):
    """Play requires 64-bit native libraries built for 16 KB pages."""
    try: z = zipfile.ZipFile(aab)
    except Exception: return None
    worst = None
    for i in z.infolist():
        if not i.filename.endswith(".so"): continue
        if "arm64" not in i.filename and "x86_64" not in i.filename: continue
        data = z.read(i)
        if data[:4] != b"\x7fELF" or data[4] != 2: continue
        phoff = struct.unpack_from("<Q", data, 0x20)[0]
        phent = struct.unpack_from("<H", data, 0x36)[0]
        phnum = struct.unpack_from("<H", data, 0x38)[0]
        for n in range(phnum):
            off = phoff + n * phent
            if struct.unpack_from("<I", data, off)[0] != 1: continue
            a = struct.unpack_from("<Q", data, off + 0x30)[0]
            worst = a if worst is None else min(worst, a)
    return worst

rows = []
for a in sorted(apps, key=lambda x: x["repo"].lower()):
    r = a["repo"]; g = asc.get(r, {}); t = tf.get(r, {}); l = lst.get(r, {}).get("uploaded", {})
    aab = sorted(glob.glob(str(D / f"{r}-*.aab")))
    align = so_alignment(aab[0]) if aab else None
    shots_ios = sum((g.get("screenshot_sets") or {}).values())
    rows.append({
        "app": r,
        "asc_record": bool(g.get("record")),
        "tf_build": g.get("build") or "—",
        "tf_testers": t.get("testers", "—"),
        "tf_review": t.get("review", "—"),
        "ios_meta": all([g.get("subtitle"), g.get("keywords"), g.get("support_url"),
                         g.get("privacy_policy_url"), (g.get("description") or 0) > 100,
                         g.get("primary_category"), g.get("age_rating")]),
        "ios_shots": shots_ios,
        "play_entry": play.get(r, {}).get("status") == "uploaded",
        "play_live": rel.get(r, {}).get("status") == "live-internal",
        "play_shots": l.get("phoneScreenshots", 0),
        "play_icon": bool(l.get("icon")),
        "play_feat": bool(l.get("featureGraphic")),
        "align16k": (align or 0) >= 16384 if align is not None else None,
    })

def yn(v): return "yes" if v is True else ("—" if v in (False, None) else str(v))
head = ["app", "ASC record", "TF build", "testers", "beta review", "iOS metadata",
        "iOS shots", "Play entry", "Play live", "Play shots", "16 KB"]
def cell(r):
    return [r["app"], yn(r["asc_record"]), str(r["tf_build"]), str(r["tf_testers"]), str(r["tf_review"]),
            yn(r["ios_meta"]), str(r["ios_shots"]), yn(r["play_entry"]), yn(r["play_live"]),
            str(r["play_shots"]), yn(r["align16k"])]
cells = [cell(r) for r in rows]
w = [max(len(head[i]), *(len(c[i]) for c in cells)) for i in range(len(head))]

L = ["# Store gates: what is met, what is not, and what only a person can do", "",
     f"Generated by `scripts/store_gates.py` on {datetime.date.today().isoformat()} from the two "
     "store APIs and the built artefacts. Do not hand-edit.", "",
     "**Nothing in this portfolio has been submitted for App Store review or released to Play "
     "production.** Apple builds go to TestFlight beta only; Android builds go to the Play "
     "internal testing track only.", "",
     "| " + " | ".join(head[i].ljust(w[i]) for i in range(len(head))) + " |",
     "|" + "|".join("-" * (w[i] + 2) for i in range(len(head))) + "|"]
L += ["| " + " | ".join(c[i].ljust(w[i]) for i in range(len(head))) + " |" for c in cells]

def names(pred): return ", ".join(r["app"] for r in rows if pred(r)) or "none"
L += ["", "## Gates a machine can still close", "",
      f"- No App Store Connect record: {names(lambda r: not r['asc_record'])}",
      f"- Record but no App Store screenshots (blocks review): "
      f"{names(lambda r: r['asc_record'] and r['ios_shots'] == 0)}",
      f"- No Play entry: {names(lambda r: not r['play_entry'])}",
      f"- Play listing under two phone screenshots (blocks production): "
      f"{names(lambda r: r['play_entry'] and r['play_shots'] < 2)}",
      "",
      "## Gates no API exposes — Play Console or App Store Connect only", "",
      "### Testing",
      "- **Play internal tester list.** The API attaches Google Groups only; the team's email "
      "list must be made in Play Console. Until then every internal release is live but "
      "reaches nobody. Internal testing is capped at 100 testers.",
      "- **TestFlight internal groups.** The API refuses tester assignment to them, so beta "
      "distribution here runs through an external group, and Apple reviews every build before "
      "testers receive it.",
      "",
      "### Production",
      "- **Apple: App Privacy details.** The nutrition label cannot be set with an API key.",
      "- **Apple: App Review sign-in.** A login-gated app needs demo credentials entered by hand.",
      "- **Apple: content rights declaration** and the submission itself.",
      "- **Play: content rating questionnaire (IARC)**, **data safety form**, **target audience "
      "and content**, **ads declaration**, **app access instructions**, and the **privacy policy "
      "URL under App content**. None of these have a Play Developer API surface.",
      "- **Play: the production release itself**, plus any upload-key reset (see MA-015).",
      "",
      "Measured platform requirements that currently pass for every built app: "
      "Android target SDK 35 or 36, and 64-bit native libraries aligned for 16 KB pages.", ""]
(M / "docs/STORE_GATES.md").write_text("\n".join(L))
print(f"wrote docs/STORE_GATES.md ({len(rows)} apps)")
