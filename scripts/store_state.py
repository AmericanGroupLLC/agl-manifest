#!/usr/bin/env python3
"""One table of where every app stands on both stores.

Reads only the result files the delivery scripts write, so it never claims
anything that was not actually observed:

  ~/agl/.dist/ios-batch/results.json      run_batch.py   (build + upload)
  ~/agl/.dist/testflight-state.json       distribute.rb --state (testers, review)
  ~/agl/.dist/play-results.json           play_upload.py (bundle upload)
  ~/agl/.dist/play-release-results.json   play_release.py (internal release live)
  ~/agl/.dist/play-listing-results.json   play_listing.py (listing + graphics)
  ~/agl/.dist/deliver-results.json        deliver_metadata.py (App Store listing)

    python3 scripts/store_state.py        # -> docs/STORE_DELIVERY_STATE.md
"""
import datetime, json, pathlib

ROOT = pathlib.Path("/Users/spatchava/agl"); M = ROOT / "agl-manifest"; D = ROOT / ".dist"
def load(p, default=None):
    p = D / p
    try: return json.load(open(p))
    except Exception: return default if default is not None else {}

apps = json.load(open(M / "apps.json"))["apps"]
ios   = load("ios-batch/results.json")
tf    = load("testflight-state.json")
play  = load("play-results.json")
rel   = load("play-release-results.json")
lst   = load("play-listing-results.json")
deliv = load("deliver-results.json")

def yn(b): return "yes" if b else "—"
rows = []
for a in sorted(apps, key=lambda x: x["repo"].lower()):
    r = a["repo"]
    rows.append((
        r,
        yn(ios.get(r, {}).get("status") == "uploaded"),
        tf.get(r, {}).get("review", "—"),
        str(tf.get(r, {}).get("testers", "—")),
        yn(deliv.get(r, {}).get("deliver") == "ok"),
        yn(play.get(r, {}).get("status") == "uploaded"),
        yn(rel.get(r, {}).get("status") == "live-internal"),
        str(lst.get(r, {}).get("uploaded", {}).get("phoneScreenshots", "—")),
    ))

head = ["app", "TestFlight", "beta review", "testers", "App Store listing",
        "Play bundle", "Play internal live", "Play shots"]
w = [max(len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(head)]
out = [f"# Store delivery state",
       "",
       f"Generated by `scripts/store_state.py` on {datetime.date.today().isoformat()} from the "
       "delivery scripts' own result files. Do not hand-edit; re-run the script.",
       "",
       "| " + " | ".join(h.ljust(w[i]) for i, h in enumerate(head)) + " |",
       "|" + "|".join("-" * (w[i] + 2) for i in range(len(head))) + "|"]
for r in rows:
    out.append("| " + " | ".join(str(c).ljust(w[i]) for i, c in enumerate(r)) + " |")
out += ["",
        f"- TestFlight uploads: {sum(1 for v in ios.values() if v.get('status') == 'uploaded')}",
        f"- Play bundles uploaded: {sum(1 for v in play.values() if v.get('status') == 'uploaded')}",
        f"- Play internal releases live: {sum(1 for v in rel.values() if v.get('status') == 'live-internal')}",
        f"- Play listings pushed: {sum(1 for v in lst.values() if v.get('status') == 'listed')}",
        f"- App Store listings delivered: {sum(1 for v in deliv.values() if v.get('deliver') == 'ok')}",
        "",
        "Blockers that need a person are in `docs/MANUAL_ACTIONS.md` (MA-014 Play tester "
        "list, MA-015 upload-key resets, MA-016 missing Play entries).", ""]
(M / "docs/STORE_DELIVERY_STATE.md").write_text("\n".join(out))
print("wrote docs/STORE_DELIVERY_STATE.md")
