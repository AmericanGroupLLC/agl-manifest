#!/usr/bin/env python3
"""Generate the Apache rewrite block that makes every policy URL resolve.

    python3 scripts/policy_aliases.py            # print the block
    python3 scripts/policy_aliases.py --apply    # write it into the site repo

The policy pages live in one directory per app, and the directory name is the
app's slug — which is not always the repo name, and not always lowercase:

    /policy/iMaps/delete-account.html               11,364 bytes, the real page
    /policy/imaps/delete-account.html              369,371 bytes, the marketing SPA

Both return HTTP 200, because `.htaccess` ends with a catch-all that serves
index.html for anything that is not a real file. So a URL with the wrong case
does not fail — it silently serves the homepage, which is what a store reviewer
sees when they click "delete my account". Google rejected iMaps' Data safety
form over exactly this class of dead link.

41 of the names someone could reasonably paste do not exist as directories:
every CamelCase repo name whose directory is lowercase, plus `imaps`,
`imeasure`, `tripnest`, `daily-pulse` and `uscis-case`. Rather than duplicate
41 directories — which then drift — this emits one redirect per alias, placed
*before* the SPA catch-all so it wins.

Generated from apps.json and the store slugs, so adding an app cannot leave a
hole behind.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from agl_paths import MANIFEST, ROOT  # noqa: E402

SITE = ROOT / "americangroup.ai"
START = "# >>> AGL policy aliases (generated by agl-manifest/scripts/policy_aliases.py)"
END = "# <<< AGL policy aliases"


def slug_for(repo: str) -> str:
    f = MANIFEST / "store/apps" / f"{repo}.json"
    if f.exists():
        return json.loads(f.read_text()).get("slug", repo.lower())
    return repo.lower()


def aliases() -> dict[str, str]:
    """alias -> canonical slug, for every name that is not already a directory."""
    apps = [a["repo"] for a in json.loads((MANIFEST / "apps.json").read_text())["apps"]]
    canonical = {slug_for(r) for r in apps}
    out: dict[str, str] = {}
    for repo in apps:
        slug = slug_for(repo)
        for cand in {repo, repo.lower(), slug.lower()}:
            if cand != slug and cand not in canonical:
                out[cand] = slug
    return dict(sorted(out.items()))


def block() -> str:
    a = aliases()
    lines = [
        START,
        "# Do not edit by hand — re-run the generator.",
        "#",
        "# Every one of these would otherwise hit the SPA catch-all below and",
        "# return the marketing homepage with HTTP 200, which reads as a working",
        "# page to a store reviewer and to any automated checker.",
        "",
        "# mod_speling fixes case on its own where it is available. The explicit",
        "# rules after it do the same job on hosts where it is not, and also",
        "# cover the aliases that are not just a case difference. None of them",
        "# carry [NC]: with it, ^policy/imaps/ would also match /policy/iMaps/",
        "# and redirect to itself forever.",
        "<IfModule mod_speling.c>",
        "    CheckSpelling On",
        "    CheckCaseOnly On",
        "</IfModule>",
        "",
    ]
    for alias, slug in a.items():
        # No [NC]. With it, ^policy/imaps/ also matches /policy/iMaps/, which
        # redirects to itself — an infinite loop, and the page becomes
        # unreachable rather than merely case-fragile. Every variant worth
        # covering is emitted explicitly instead.
        lines.append(f"RewriteRule ^policy/{alias}/(.*)$ /policy/{slug}/$1 [R=301,L]")
        lines.append(f"RewriteRule ^policy/{alias}/?$ /policy/{slug}/ [R=301,L]")
    lines += ["", END, ""]
    return "\n".join(lines)


def splice(text: str, new_block: str) -> str:
    """Put the block in, before the SPA catch-all, replacing any previous copy."""
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        return head + new_block.rstrip("\n") + "\n" + tail.lstrip("\n")

    marker = "# ── React SPA Routing"
    if marker in text:
        i = text.index(marker)
        return text[:i] + new_block + "\n" + text[i:]
    # No recognisable catch-all: appending would put the rules after it and
    # they would never run. Refuse rather than write something that looks
    # applied and is not.
    raise SystemExit("could not find the SPA routing block; not writing blind")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    a = aliases()
    b = block()
    if not args.apply:
        print(b)
        print(f"# {len(a)} aliases", file=sys.stderr)
        return 0

    targets = [SITE / "client/public/.htaccess", SITE / ".htaccess"]
    wrote = []
    for t in targets:
        if not t.exists():
            print(f"  skip (absent): {t}")
            continue
        t.write_text(splice(t.read_text(), b))
        wrote.append(t)
    print(f"{len(a)} aliases written into {len(wrote)} file(s):")
    for t in wrote:
        print(f"  {t}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
