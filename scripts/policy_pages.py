#!/usr/bin/env python3
"""Generate the per-app policy site under www.safecodeg.com/client/public/policy/.

Every store listing needs a privacy-policy URL and a support URL that resolve.
Pages are written from *measured* facts — apps.json (auth providers, ads), each
app's Info.plist usage strings and AndroidManifest permissions, and pubspec
dependencies — never from what an app is imagined to do.

    python3 scripts/policy_pages.py            # write missing pages, refresh landing
    python3 scripts/policy_pages.py --force    # rewrite generated pages too

Hand-written pages already on the site are never overwritten: a file is only
written when it is absent, or when it carries the GENERATED marker and --force
is given. The slug map below pins each app to its existing directory so live
URLs stay stable.
"""
import json, pathlib, plistlib, re, sys, html, datetime

ROOT = pathlib.Path("/Users/spatchava/agl")
MANIFEST = ROOT / "agl-manifest"
SITE = ROOT / "www.safecodeg.com/client/public/policy"
MARK = "<!-- GENERATED by agl-manifest/scripts/policy_pages.py — edit the generator, or remove this line to hand-maintain -->"
FORCE = "--force" in sys.argv
TODAY = datetime.date.today().strftime("%B %Y")

# repo -> existing directory name (keeps URLs that are already live)
SLUGS = {
    "TripNest": "TripNest", "AGrammarly": "agrammarly", "BodyQuest": "bodyquest", "CalcMaster": "calcmaster",
    "CarDeal": "cardeal", "daily-pulse": "dailypulse", "DriftDate": "driftdate", "FashionFactory": "fashionfactory",
    "GroceryMatch": "grocerymatch", "HerJourney": "herjourney", "iMaps": "iMaps", "iMeasure": "iMeasure",
    "MyHealth": "myhealth", "Photriya": "photriya", "PilotEnRoute": "pilotenroute", "radiotune": "radiotune",
    "Uscis-Case": "uscis-case-tracker", "Verba": "verba", "VirtuBand": "virtuband",
}
def slug_for(repo): return SLUGS.get(repo, repo.lower())

apps = json.load(open(MANIFEST / "apps.json"))["apps"]

def store_copy(repo):
    p = MANIFEST / "store/apps" / f"{repo}.json"
    return json.load(open(p))["copy"]["en"] if p.exists() else {}

def facts(a):
    d = ROOT / a["repo"] / (a["dir"] if a["dir"] != "." else "")
    pl = plistlib.load(open(d / "ios/Runner/Info.plist", "rb"))
    usage = {k: v for k, v in pl.items() if k.endswith("UsageDescription") and isinstance(v, str) and v.strip()}
    man = d / "android/app/src/main/AndroidManifest.xml"
    perms = sorted(set(p.split(".")[-1] for p in re.findall(r'uses-permission[^>]*android:name="([^"]+)"', man.read_text()))) if man.exists() else []
    deps = (d / "pubspec.yaml").read_text().split("dev_dependencies")[0]
    dep = lambda k: re.search(rf"^\s+{k}:", deps, re.M) is not None
    return dict(usage=usage, perms=perms, iap=dep("in_app_purchase") or dep("purchases_flutter"),
                ads=a["ads"] or dep("google_mobile_ads"), supabase=dep("supabase_flutter"),
                google=dep("google_sign_in"), apple=dep("sign_in_with_apple"), biometric=dep("local_auth"),
                speech=dep("speech_to_text"), health=dep("health"), providers=a["auth"]["providers"],
                network="INTERNET" in perms)

USAGE_LABEL = {
    "NSCameraUsageDescription": "Camera", "NSMicrophoneUsageDescription": "Microphone",
    "NSLocationWhenInUseUsageDescription": "Location (while using the app)", "NSLocationAlwaysUsageDescription": "Location (always)",
    "NSLocationAlwaysAndWhenInUseUsageDescription": "Location (always and while using)", "NSPhotoLibraryUsageDescription": "Photo library",
    "NSPhotoLibraryAddUsageDescription": "Save to photo library", "NSUserTrackingUsageDescription": "App Tracking Transparency",
    "NSSpeechRecognitionUsageDescription": "Speech recognition", "NSMotionUsageDescription": "Motion sensors",
    "NSHealthShareUsageDescription": "Health data (read)", "NSHealthUpdateUsageDescription": "Health data (write)",
    "NSFaceIDUsageDescription": "Face ID", "NSLocalNetworkUsageDescription": "Local network",
    "NSBluetoothAlwaysUsageDescription": "Bluetooth", "NSBluetoothPeripheralUsageDescription": "Bluetooth peripherals",
}

def page(title, app_name, slug, body, nav_extra=""):
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{html.escape(title)} · {html.escape(app_name)}</title>
  <link rel="stylesheet" href="styles.css">
</head>
<body>
  {MARK}
  <div class="wrap">
    <header class="top">
      <a class="logo" href="index.html">{html.escape(app_name)}</a>
      <nav>
        <a href="index.html">Privacy</a>
        <a href="terms.html">Terms</a>
        <a href="support.html">Support</a>{nav_extra}
      </nav>
    </header>
    <article>
{body}
    </article>
    <footer><p>© {datetime.date.today().year} American Group LLC · <a href="https://safecodeg.com">safecodeg.com</a> · <a href="mailto:contact@safecodeg.com">contact@safecodeg.com</a></p></footer>
  </div>
</body>
</html>
"""

def privacy(a, f, name, slug):
    e = html.escape
    has_account = bool(set(f["providers"]) & {"Supabase", "Google", "Apple", "Firebase"}) or f["supabase"]
    s = [f"<h2>Privacy Policy</h2>", f"<p><em>Last updated: {TODAY}</em></p>",
         f"<p>This policy applies to <strong>{e(name)}</strong>, developed and published by American Group LLC, on iOS and Android.</p>",
         "<table><tbody>",
         f"<tr><td><strong>Application</strong></td><td>{e(name)}</td></tr>",
         f"<tr><td><strong>iOS bundle id</strong></td><td>{e(a['bundle_id'])}</td></tr>",
         f"<tr><td><strong>Android package</strong></td><td>{e(a['application_id'])}</td></tr>",
         "<tr><td><strong>Developer</strong></td><td>American Group LLC</td></tr>",
         "<tr><td><strong>Contact</strong></td><td><a href=\"mailto:contact@safecodeg.com\">contact@safecodeg.com</a></td></tr>",
         "</tbody></table>"]
    s.append("<h3>Accounts</h3>")
    if has_account:
        prov = [p for p in ["Google", "Apple"] if p in f["providers"] or (p == "Google" and f["google"]) or (p == "Apple" and f["apple"])]
        via = " or ".join(f"Sign in with {p}" for p in prov) if prov else "email"
        s.append(f"<p>You may create an account with {e(via)}. When you do, we receive the identifier the provider returns, your email address, and the display name you choose. Accounts are stored with Supabase (Supabase Inc.) under an encrypted connection. "
                 + ("The app can be used without an account." if a["auth"].get("account_optional") else "An account is required for the features that save data to your profile.")
                 + " You can delete your account and its data at any time — see <a href=\"delete-account.html\">Delete your account</a>.</p>")
    elif f["biometric"]:
        s.append("<p>The app does not create accounts. Face ID, Touch ID or Android biometrics unlock data that is stored only on your device; biometric data itself never leaves the operating system and is never seen by the app or by us.</p>")
    else:
        s.append("<p>The app does not require registration and does not create user accounts or profiles.</p>")
    s.append("<h3>Device permissions</h3>")
    if f["usage"]:
        s.append("<p>The app asks for the following permissions only when you use the related feature, and each request explains its purpose with the text below. You can decline any of them and keep using the rest of the app.</p><ul>")
        for k, v in sorted(f["usage"].items()):
            s.append(f"<li><strong>{e(USAGE_LABEL.get(k, k))}</strong> — {e(v)}</li>")
        s.append("</ul>")
    else:
        s.append("<p>The app requests no camera, microphone, location, photo, contact or health permissions.</p>")
    if f["perms"]:
        s.append(f"<p>Android permissions declared: <code>{e(', '.join(f['perms']))}</code>.</p>")
    if f["health"]:
        s.append("<p><strong>Health data</strong> read through Apple HealthKit or Android Health Connect is used only to show it to you inside the app and is never used for advertising or shared with third parties.</p>")
    s.append("<h3>Advertising</h3>")
    if f["ads"]:
        s.append("<p>The app shows ads served by Google Mobile Ads (AdMob). Google may use the device advertising identifier to serve and measure ads, as described in <a href=\"https://policies.google.com/privacy\">Google's privacy policy</a>. Where required, the app asks for your consent before any ad is requested, and you can change that choice in the app's settings. We do not sell your personal information.</p>")
    else:
        s.append("<p>The app does not show advertisements and does not include an advertising SDK.</p>")
    s.append("<h3>Purchases</h3>")
    s.append("<p>Optional in-app purchases and subscriptions are processed by Apple or Google. We never receive your payment card details. Manage or cancel subscriptions in your App Store or Google Play account settings.</p>" if f["iap"]
             else "<p>The app has no in-app purchases.</p>")
    if f["speech"]:
        s.append("<h3>Speech recognition</h3><p>Voice input is converted to text by the speech-recognition service of your device's operating system, which may send audio to Apple or Google for processing under their terms.</p>")
    s.append("<h3>Analytics and crash reporting</h3><p>This release sends no analytics and no crash reports to us. If a future version enables crash reporting, this page will be updated first.</p>")
    s.append("<h3>Network</h3>")
    s.append("<p>The app connects to the internet to provide its features" + (" and to your account backend" if has_account else "") + ". Connections use HTTPS.</p>" if f["network"] or has_account
             else "<p>The app declares no network permission on Android and works entirely on your device.</p>")
    s.append("<h3>Data retention and deletion</h3>")
    s.append("<p>Account data is kept until you delete your account, after which it is removed from our systems within 30 days. Anything stored only on your device is removed when you uninstall the app." if has_account
             else "<p>Data the app stores lives on your device and is removed when you uninstall the app.</p>")
    s.append("<h3>Children</h3><p>The app is not directed to children under 13 and we do not knowingly collect personal information from them.</p>")
    s.append("<h3>Your rights</h3><p>You may ask us to access, correct or delete personal data we hold about you by emailing <a href=\"mailto:contact@safecodeg.com\">contact@safecodeg.com</a>. We answer within 30 days.</p>")
    s.append("<h3>Changes</h3><p>We will post any change to this policy on this page with a new date.</p>")
    s.append("<h3>Contact</h3><p>American Group LLC · <a href=\"https://safecodeg.com\">safecodeg.com</a> · <a href=\"mailto:contact@safecodeg.com\">contact@safecodeg.com</a></p>")
    return "\n".join(s)

